export function localizeDocs(docs, categories, locale) {
  const catMap = categoryLabels[locale] || categoryLabels.en;
  const descMap = docDescriptions[locale] || {};
  const localizedCategories = categories.map((c) => catMap[c] || c);
  const localizedDocs = docs.map((doc) => ({
    ...doc,
    categoryLabel: catMap[doc.category] || doc.category,
    description: descMap[doc.name] || doc.description,
  }));
  return { localizedCategories, localizedDocs, catMap };
}
